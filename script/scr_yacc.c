int yy_get_next_buffer()
{
	register char *dest = yy_current_buffer->yy_ch_buf;
	register char *source = yytext;
	register int number_to_move, i;
	int ret_val;

	if ( yy_c_buf_p > &yy_current_buffer->yy_ch_buf[yy_n_chars + 1] )
		yy_fatal_error( "fatal flex scanner internal error--end of buffer missed" );

	if ( yy_current_buffer->yy_fill_buffer == 0 )
	{
		/* Don't try to fill the buffer, so this is an EOF. */
		if ( yy_c_buf_p - yytext - YY_MORE_ADJ == 1 )
			return EOB_ACT_END_OF_FILE;
		else
			return EOB_ACT_LAST_MATCH;
	}

	/* Try to read more data. */

	/* First move last chars to start of buffer. */
	number_to_move = (int) (yy_c_buf_p - yytext) - 1;

	for ( i = 0; i < number_to_move; ++i )
		*(dest++) = *(source++);

	if ( yy_current_buffer->yy_buffer_status == YY_BUFFER_EOF_PENDING )
		/* don't do the read, it's not guaranteed to return an EOF,
		 * just force an EOF
		 */
		yy_current_buffer->yy_n_chars = yy_n_chars = 0;

	else
	{
		int num_to_read = yy_current_buffer->yy_buf_size - number_to_move - 1;

		while ( num_to_read <= 0 )
		{
			/* Not enough room in the buffer - grow it. */
			yy_buffer_state *b = yy_current_buffer;

			int yy_c_buf_p_offset = (int) (yy_c_buf_p - b->yy_ch_buf);

			if ( b->yy_is_our_buffer )
			{
				int new_size = b->yy_buf_size * 2;

				if ( new_size <= 0 )
					b->yy_buf_size += b->yy_buf_size / 8;
				else
					b->yy_buf_size *= 2;

				b->yy_ch_buf = (char *) yy_flex_realloc( (void *) b->yy_ch_buf, b->yy_buf_size + 2 );
			}
			else
				/* Can't grow it, we don't own it. */
				b->yy_ch_buf = 0;

			if ( ! b->yy_ch_buf )
				yy_fatal_error( "fatal error - scanner input buffer overflow" );

			yy_c_buf_p = &b->yy_ch_buf[yy_c_buf_p_offset];

			num_to_read = yy_current_buffer->yy_buf_size - number_to_move - 1;
		}

		if ( num_to_read > YY_READ_BUF_SIZE )
			num_to_read = YY_READ_BUF_SIZE;

		/* Read in more data. */
		yy_n_chars = Scr_ScanFile(&yy_current_buffer->yy_ch_buf[number_to_move], num_to_read);

		yy_current_buffer->yy_n_chars = yy_n_chars;
	}

	if ( yy_n_chars == 0 )
	{
		if ( number_to_move == YY_MORE_ADJ )
		{
			ret_val = EOB_ACT_END_OF_FILE;
			yyrestart( yyin );
		}

		else
		{
			ret_val = EOB_ACT_LAST_MATCH;
			yy_current_buffer->yy_buffer_status = YY_BUFFER_EOF_PENDING;
		}
	}

	else
		ret_val = EOB_ACT_CONTINUE_SCAN;

	yy_n_chars += number_to_move;
	yy_current_buffer->yy_ch_buf[yy_n_chars] = YY_END_OF_BUFFER_CHAR;
	yy_current_buffer->yy_ch_buf[yy_n_chars + 1] = YY_END_OF_BUFFER_CHAR;

	yytext = &yy_current_buffer->yy_ch_buf[0];

	return ret_val;
}

/* yy_get_previous_state - get the state just before the EOB char was reached */
int yy_get_previous_state()
{
	register int yy_current_state;
	register char *yy_cp;
	register unsigned char yy_c;

	yy_current_state = yy_start;

	for ( yy_cp = yytext + YY_MORE_ADJ; yy_cp < yy_c_buf_p; yy_cp++ )
	{
		if ( *yy_cp )
			yy_c = yy_ec[YY_SC_TO_UI(*yy_cp)];
		else
			yy_c = 1;

		if ( yy_accept[yy_current_state] )
		{
			yy_last_accepting_state = yy_current_state;
			yy_last_accepting_cpos = yy_cp;
		}
		while ( yy_chk[yy_base[yy_current_state] + yy_c] != yy_current_state )
		{
			yy_current_state = (int) yy_def[yy_current_state];
			if ( yy_current_state >= 256 )
				yy_c = yy_meta[(unsigned int) yy_c];
		}
		yy_current_state = yy_nxt[yy_base[yy_current_state] + (unsigned int) yy_c];
	}

	return yy_current_state;
}

/* yy_try_NUL_trans - try to make a transition on the NUL character
 *
 * synopsis
 *	next_state = yy_try_NUL_trans( current_state );
 */
int yy_try_NUL_trans( int yy_current_state )
{
	register int yy_is_jam;
	char *yy_cp = yy_c_buf_p;
	unsigned char yy_c = 1;

	if ( yy_accept[yy_current_state] )
	{
		yy_last_accepting_state = yy_current_state;
		yy_last_accepting_cpos = yy_cp;
	}
	while ( yy_chk[yy_base[yy_current_state] + yy_c] != yy_current_state )
	{
		yy_current_state = (int) yy_def[yy_current_state];
		if ( yy_current_state >= 256 )
			yy_c = yy_meta[(unsigned int) yy_c];
	}
	yy_current_state = yy_nxt[yy_base[yy_current_state] + (unsigned int) yy_c];

	yy_is_jam = (yy_current_state == 255);

	return yy_is_jam ? 0 : yy_current_state;
}

/*
==============
yyinput
==============
*/
int yyinput()
{
	int c;

	*yy_c_buf_p = yy_hold_char;

	if ( *yy_c_buf_p == YY_END_OF_BUFFER_CHAR )
	{
		/* yy_c_buf_p now points to the character we want to return.
		 * If this occurs *before* the EOB characters, then it's a
		 * valid NUL; if not, then we've hit the end of the buffer.
		 */
		if ( yy_c_buf_p < &yy_current_buffer->yy_ch_buf[yy_n_chars] )
			/* This was really a NUL. */
			*yy_c_buf_p = '\0';

		else
		{ /* need more input */
			int offset = yy_c_buf_p - yytext;
			++yy_c_buf_p;

			switch ( yy_get_next_buffer() )
			{
				case EOB_ACT_LAST_MATCH:
					yyrestart( yyin );

					/* fall through */

				case EOB_ACT_END_OF_FILE:
				{
					if ( yywrap() )
						return EOF;

					if ( ! yy_did_buffer_switch_on_eof )
						yyrestart( yyin );
					return yyinput();
				}

				case EOB_ACT_CONTINUE_SCAN:
					yy_c_buf_p = yytext + offset;
					break;
			}
		}
	}

	c = *(unsigned char *) yy_c_buf_p;	/* cast for 8-bit char's */
	*yy_c_buf_p = '\0';	/* preserve yytext */
	yy_hold_char = *++yy_c_buf_p;

	return c;
}

/*
==============
yyrestart
==============
*/
void yyrestart( FILE *input_file )
{
	if ( ! yy_current_buffer )
		yy_current_buffer = yy_create_buffer( yyin, YY_BUF_SIZE );

	yy_init_buffer( yy_current_buffer, input_file );
	yy_load_buffer_state();
}

/*
==============
yy_switch_to_buffer
==============
*/
void yy_switch_to_buffer( yy_buffer_state *new_buffer )
{
	if ( yy_current_buffer == new_buffer )
		return;

	if ( yy_current_buffer )
	{
		/* Flush out information for old buffer. */
		*yy_c_buf_p = yy_hold_char;
		yy_current_buffer->yy_buf_pos = yy_c_buf_p;
		yy_current_buffer->yy_n_chars = yy_n_chars;
	}

	yy_current_buffer = new_buffer;
	yy_load_buffer_state();

	/* We don't actually know whether we did this switch during
	 * EOF (yywrap()) processing, but the only time this flag
	 * is looked at is after yywrap() is called, so it's safe
	 * to go ahead and always set it.
	 */
	yy_did_buffer_switch_on_eof = 1;
}

/*
==============
yy_load_buffer_state
==============
*/
void yy_load_buffer_state()
{
	yy_n_chars = yy_current_buffer->yy_n_chars;
	yytext = yy_c_buf_p = yy_current_buffer->yy_buf_pos;
	yyin = yy_current_buffer->yy_input_file;
	yy_hold_char = *yy_c_buf_p;
}

/*
==============
yy_create_buffer
==============
*/
yy_buffer_state *yy_create_buffer( FILE *file, int size )
{
	yy_buffer_state *b;

	b = (yy_buffer_state*) yy_flex_alloc( sizeof( *b ) );
	if ( ! b )
		yy_fatal_error( "out of dynamic memory in yy_create_buffer()" );

	b->yy_buf_size = size;

	/* yy_ch_buf has to be 2 characters longer than the size given because
	 * we need to put in 2 end-of-buffer characters.
	 */
	b->yy_ch_buf = (char *) yy_flex_alloc( b->yy_buf_size + 2 );
	if ( ! b->yy_ch_buf )
		yy_fatal_error( "out of dynamic memory in yy_create_buffer()" );

	b->yy_is_our_buffer = 1;

	yy_init_buffer( b, file );

	return b;
}

/*
==============
yy_delete_buffer
==============
*/
void yy_delete_buffer( yy_buffer_state *b )
{
	if ( ! b )
		return;

	if ( b == yy_current_buffer )
		yy_current_buffer = (yy_buffer_state *) 0;

	if ( b->yy_is_our_buffer )
		yy_flex_free( (void *) b->yy_ch_buf );

	yy_flex_free( (void *) b );
}

/*
==============
yy_init_buffer
==============
*/
void yy_init_buffer( yy_buffer_state *b, FILE *file )
{
	yy_flush_buffer( b );

	b->yy_input_file = file;
	b->yy_fill_buffer = 1;

	b->yy_is_interactive = file ? (isatty( fileno(file) ) > 0) : 0;
}

void yy_flush_buffer( yy_buffer_state *b )
{
	if ( !b )
		return;

	b->yy_n_chars = 0;

	/* We always need two end-of-buffer characters.  The first causes
	 * a transition to the end-of-buffer state.  The second causes
	 * a jam in that state.
	 */
	b->yy_ch_buf[0] = YY_END_OF_BUFFER_CHAR;
	b->yy_ch_buf[1] = YY_END_OF_BUFFER_CHAR;

	b->yy_buf_pos = &b->yy_ch_buf[0];

	b->yy_at_bol = 1;
	b->yy_buffer_status = YY_BUFFER_NEW;

	if ( b == yy_current_buffer )
		yy_load_buffer_state();
}

/*
==============
yy_scan_buffer
==============
*/
yy_buffer_state *yy_scan_buffer( char *base, unsigned int size )
{
	yy_buffer_state *b;

	if ( size < 2 ||
	     base[size-2] != YY_END_OF_BUFFER_CHAR ||
	     base[size-1] != YY_END_OF_BUFFER_CHAR )
		/* They forgot to leave room for the EOB's. */
		return 0;

	b = (yy_buffer_state *) yy_flex_alloc( sizeof( yy_buffer_state ) );
	if ( ! b )
		yy_fatal_error( "out of dynamic memory in yy_scan_buffer()" );

	b->yy_buf_size = size - 2;	/* "- 2" to take care of EOB's */
	b->yy_buf_pos = b->yy_ch_buf = base;
	b->yy_is_our_buffer = 0;
	b->yy_input_file = 0;
	b->yy_n_chars = b->yy_buf_size;
	b->yy_is_interactive = 0;
	b->yy_at_bol = 1;
	b->yy_fill_buffer = 0;
	b->yy_buffer_status = YY_BUFFER_NEW;

	yy_switch_to_buffer( b );

	return b;
}

/*
==============
yy_scan_string
==============
*/
yy_buffer_state *yy_scan_string( const char *yy_str )
{
	int len;
	for ( len = 0; yy_str[len]; ++len )
		;

	return yy_scan_bytes( yy_str, len );
}

/*
==============
yy_scan_bytes
==============
*/
yy_buffer_state *yy_scan_bytes( const char *bytes, int len )
{
	yy_buffer_state *b;
	char *buf;
	unsigned int n;
	int i;

	/* Get memory for full buffer, including space for trailing EOB's. */
	n = len + 2;
	buf = (char *) yy_flex_alloc( n );
	if ( ! buf )
		yy_fatal_error( "out of dynamic memory in yy_scan_bytes()" );

	for ( i = 0; i < len; ++i )
		buf[i] = bytes[i];

	buf[len] = buf[len+1] = YY_END_OF_BUFFER_CHAR;

	b = yy_scan_buffer( buf, n );
	if ( ! b )
		yy_fatal_error( "bad buffer in yy_scan_bytes()" );

	/* It's okay to grow etc. this buffer, and we should throw it
	 * away when we're done.
	 */
	b->yy_is_our_buffer = 1;

	return b;
}

